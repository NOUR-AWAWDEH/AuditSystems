using Microsoft.AspNetCore.Identity;
using AuditSystem.Domain.Entities.Users;

namespace AuditSystem.Auth.Services.Password.ResetPassword;

/// <summary>
/// Service for securely resetting user passwords using ASP.NET Identity.
/// This implementation uses Identity's built-in token validation for maximum security.
/// </summary>
public class PasswordResetService(UserManager<ApplicationUser> userManager) : IPasswordResetService
{
    /// <summary>
    /// Resets a user's password using a secure token.
    /// Identity automatically validates the token (expiration, one-time use, tampering).
    /// </summary>
    /// <param name="user">The user whose password is being reset.</param>
    /// <param name="token">The secure reset token generated by IPasswordTokenService.</param>
    /// <param name="newPassword">The new password (must meet password policy requirements).</param>
    /// <returns>IdentityResult with success status and any validation errors.</returns>
    public async Task<IdentityResult> ResetPasswordAsync(ApplicationUser user, string token, string newPassword)
    {
        if (user == null)
            return IdentityResult.Failed(new IdentityError { Description = "User not found." });

        if (string.IsNullOrWhiteSpace(token))
            return IdentityResult.Failed(new IdentityError { Description = "Invalid reset token." });

        if (string.IsNullOrWhiteSpace(newPassword))
            return IdentityResult.Failed(new IdentityError { Description = "Password cannot be empty." });

        // Identity validates token expiration, one-time use, and tampering automatically
        return await userManager.ResetPasswordAsync(user, token, newPassword);
    }
}